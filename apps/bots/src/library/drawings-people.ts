type Drawing = () => DrawOp[];

/** Head circle plus eyes and a mouth, used by the character drawings. */
function head(cx: number, cy: number, r: number, smile = true): DrawOp[] {
  const ops = [
    circle(cx, cy, r),
    dot(cx - r * 0.35, cy - r * 0.15, 10),
    dot(cx + r * 0.35, cy - r * 0.15, 10),
  ];
  if (smile) ops.push(arc(cx, cy + r * 0.2, r * 0.45, 0.3, PI - 0.3, THIN, 10));
  return ops;
}

/** Simple robe/dress trapezoid under a head. */
function robe(
  cx: number,
  top: number,
  bottom: number,
  topW: number,
  bottomW: number,
  s = {},
): DrawOp {
  return polygon(
    [
      [cx - topW / 2, top],
      [cx + topW / 2, top],
      [cx + bottomW / 2, bottom],
      [cx - bottomW / 2, bottom],
    ],
    s,
  );
}

